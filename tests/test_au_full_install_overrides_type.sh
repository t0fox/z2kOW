#!/bin/sh
# tests/test_au_full_install_overrides_type.sh
#
# ЧТО ОХРАНЯЕТСЯ: выпуск, помеченный `full_install`, ставится ПОЛНОЙ
# ПЕРЕУСТАНОВКОЙ независимо от того, какой у него тип.
#
# ОТКУДА ПРАВИЛО. Флаг ставится сам по смене пина движка (lib/release_map.sh,
# z2k_engine_pin_changed), а ТИП релиза при этом остаётся тем, который назвал
# человек, — как правило `patch`. Апдейтер на флаге уходит с адресного пути на
# старый, а старый выбирал действие по ТИПУ: видел `patch` и раскладывал файлы.
# Полный установщик не запускался, значит архив форка не скачивался и движок
# оставался прежним.
#
# Цена: движок живёт релизом форка, в нашем дереве от него одна строка с
# адресом архива, и доставить его адресными шагами нечем. p-84.11 (14.09.2026)
# уехал именно так — новые детекторы приехали на СТАРОЕ ядро ротации, где нет
# ни привязки вердикта к поколению, ни circular_report_failure. Обход не умер
# (обращения к новому API закрыты проверкой типа), но смысл выпуска не доехал,
# а понизившийся порог retrans=2 остался — на старом ядре это больше ложных
# ротаций, а не меньше.
#
# Настоящие функции апдейтера гоняются на подставном манифесте; наружу (сеть,
# установщик, блокировки) выведены заглушки.
# POSIX sh.

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }

SB=$(mktemp -d) || exit 1
trap 'rm -rf "$SB"' EXIT INT TERM

Z2K_AU_SOURCE_ONLY=1; export Z2K_AU_SOURCE_ONLY
# shellcheck disable=SC1091
. "$ROOT/lib/utils.sh" 2>/dev/null
# shellcheck disable=SC1091
. "$ROOT/lib/auto_update.sh" 2>/dev/null

# ВСЁ ГЛОБАЛЬНОЕ СОСТОЯНИЕ — В ПЕСОЧНИЦУ, И ЭТО НЕ ПЕДАНТИЗМ.
#
# Умолчания апдейтера указывают в /opt/zapret2: маркер «дерево смешанное»,
# замок, отметка версии. На машине разработчика этот каталог не пишется, и
# набор проходил; на раннере CI пишется — и мой прогон оставлял там маркер,
# который ПАРАЛЛЕЛЬНО читал соседний набор test_auto_update_decide и получал
# «вердикт принудительно reinstall» вместо patch. Красный CI на p-84.12 и
# p-84.13 был именно этим: свой тест уронил чужой через общий файл.
Z2K_AU_TMP_DIR="$SB/tmp"; mkdir -p "$Z2K_AU_TMP_DIR"
Z2K_AU_DIRTY_TREE_FILE="$SB/tree-dirty"
Z2K_AU_LOCK_FILE="$SB/update.lock"
export Z2K_AU_TMP_DIR Z2K_AU_DIRTY_TREE_FILE Z2K_AU_LOCK_FILE

# Цель из карты установки обязана СУЩЕСТВОВАТЬ на диске, и это не декорация
# фикстуры. Апдейтер сверяется со сходимостью: файл, который карта обещает, а на
# диске его нет, патчем не доставить — и он честно назначает полную
# переустановку. Без этой строки четвёртый случай ниже («обычный выпуск
# остаётся патчем») падал в CI и проходил на машине разработчика, то есть
# проверял не то, что написано в его названии.
mkdir -p "$SB/zd"
printf 'файл на месте\n' > "$SB/zd/a.lua"
Z2K_AU_INSTALLED_TAG_FILE="$SB/installed_tag"
printf 'p-1\n' > "$Z2K_AU_INSTALLED_TAG_FILE"

# Манифест: тип patch, но флаг полной переустановки. install_map и files_sha256
# нужны, чтобы апдейтер дошёл до адресной ветки — именно там и стоит развилка.
mk_manifest() {
    # $1 — значение full_install: true | отсутствует
    _fi=""
    [ "$1" = "true" ] && _fi=', "full_install": true'
    cat > "$Z2K_AU_TMP_DIR/UPDATES.json" <<MAN
{
  "schema": 1,
  "branch": "z2k-enhanced",
  "current": "p-2",
  "install_map": { "files/lua/a.lua": ["$SB/zd/a.lua"] },
  "files_sha256": { "files/lua/a.lua": "0000" },
  "history": [
{"v": "p-1", "type": "patch", "ts": "2026-09-01T00:00:00Z", "ref": "p-1", "desc": ".", "changed_files": ["files/lua/a.lua"], "steps": ["restart-service"]},
{"v": "p-2", "type": "patch", "ts": "2026-09-14T00:00:00Z", "ref": "p-2", "desc": ".", "changed_files": ["files/lua/a.lua"], "steps": ["restart-service"]$_fi}
  ]
}
MAN
}

# Заглушки наружу: сеть, блокировки, снимки, установка.
au_fetch_manifest() { :; }
au_log() { :; }
au_lock_acquire() { :; }
au_lock_release() { :; }
au_snapshot_services() { :; }
au_snapshot_for_patch() { :; }
au_health_check() { :; }
au_write_installed_tag() { :; }
au_mark_version() { :; }
au_apply_patch()     { echo "ВЫБРАН=patch"     > "$SB/chosen"; return 0; }
au_apply_reinstall() { echo "ВЫБРАН=reinstall" > "$SB/chosen"; return 0; }

run_apply() { : > "$SB/chosen"; au_run_apply >/dev/null 2>&1; cat "$SB/chosen" 2>/dev/null; }

# --- 1. флаг стоит -> полная переустановка ----------------------------------
mk_manifest true
_got=$(run_apply)
case "$_got" in
    *reinstall*) ok "full_install: выбрана полная переустановка, а не патч" ;;
    *) no "full_install -> полная переустановка" "ВЫБРАН=reinstall" "${_got:-ничего}" ;;
esac

# --- 2. флага нет -> полной переустановки НЕ случается -----------------------
# Обычный выпуск уходит адресным путём и до старой развилки вообще не доходит,
# поэтому здесь важно не «выбран патч», а «переустановку никто не назначил»:
# иначе правка выше превратила бы в переустановку каждый выпуск.
mk_manifest no
_got=$(run_apply)
case "$_got" in
    *reinstall*) no "без флага переустановки быть не должно" "не reinstall" "$_got" ;;
    *) ok "без флага выпуск не превращается в переустановку" ;;
esac

# --- 3. проверка обновлений не называет такой выпуск патчем ------------------
# Человеку, которому написали PATCH, а потом переустановили всё дерево, мы
# соврали.
mk_manifest true
_out=$(au_run_check 2>&1)
case "$_out" in
    *REINSTALL*) ok "проверка обновлений честно говорит REINSTALL" ;;
    *PATCH*)     no "проверка обновлений называет тип честно" "REINSTALL" "PATCH" ;;
    *)           no "проверка обновлений что-то сказала" "REINSTALL" "${_out:-пусто}" ;;
esac

# Обратной проверки — «обычный выпуск проверка зовёт PATCH» — здесь НЕТ, и это
# осознанно. Как назвать обычный выпуск, решает au_decide, а он рассуждает о
# сходимости: цели карты установки, известность шагов, состояние дерева. Эта
# фикстура таких вещей не моделирует, и в CI проверка падала на «REINSTALL» по
# причинам, к правке отношения не имеющим. Пинить тут — значит пинить фикстуру,
# а не поведение продукта; ветку «флаг стоит» закрывает случай выше.

# --- 4. неизвестная установленная версия: обещать переустановку нельзя -------
#
# au_decide на версии, которой нет в истории, отвечает «none» — вслепую
# переустанавливать он не станет. Переопределение по флагу обязано это уважать,
# иначе человек читает «Доступно обновление (REINSTALL) до » с пустой версией,
# а на деле не произойдёт ничего.
mk_manifest true
printf 'unknown-tag-999\n' > "$Z2K_AU_INSTALLED_TAG_FILE"
_out=$(au_run_check 2>&1)
case "$_out" in
    *REINSTALL*) no "неизвестная версия: переустановка не обещается" "без REINSTALL" "$_out" ;;
    *)           ok "неизвестная версия: переустановка не обещается" ;;
esac
printf 'p-1\n' > "$Z2K_AU_INSTALLED_TAG_FILE"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
