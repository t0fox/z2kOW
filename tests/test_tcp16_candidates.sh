#!/bin/sh
# tests/test_tcp16_candidates.sh — перебор имён для блока по объёму: порядок и
# состав списка кандидатов.
#
# ЧТО ЗДЕСЬ ОХРАНЯЕТСЯ.
#
# 1. Перебор идёт СВЕРХУ ВНИЗ и останавливается на первом подошедшем имени, а
#    карта «сеть -> имя» пересобирается КАЖДУЮ НОЧЬ с нуля. Значит сеть, чьё имя
#    лежит в хвосте, каждую ночь платит за весь путь до него заново: замер
#    16.09.2026 — louisvuitton.com для AS20860 стоит 1247-м, это двенадцать
#    минут перебора ради значения, которое уже известно. Поэтому проба обязана
#    начинать с имён, которые уже стоят в карте.
# 2. Эмпирический порядок первых имён трогать нельзя: он решает большинство
#    сетей за десятки проб. Новый список (сам белый список целиком) добавлен
#    хвостом — за глубину платят только сети без имени.
# 3. Дубли в склеенном списке — это лишние пробы к чужим серверам с нашей
#    линии, поэтому склейка обязана их убирать.
#
# Проверяется ИСПОЛНЕНИЕМ: кусок пробы вырезается из файла и запускается на
# поддельных картах. Грепом «сначала известные имена» не проверить.
#
# POSIX sh.

HERE=$(cd "$(dirname "$0")/.." && pwd)
PROBE="$HERE/files/z2k-tcp16-probe.sh"
CANDS="$HERE/files/lists/sni_wl_candidates.txt"
TARGETS="$HERE/files/lists/tcp16_targets.txt"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }

for f in "$PROBE" "$CANDS" "$TARGETS"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

T=$(mktemp -d "${TMPDIR:-/tmp}/tcp16cand.XXXXXX") || exit 1
trap 'rm -rf "$T"' EXIT

# --- 1. Склейка: известные имена впереди, дублей нет -------------------------
#
# Вырезаем ровно ту склейку, что стоит в пробе, и кормим её поддельными картой
# и списком. Подстановки путей — через те же имена переменных, что в скрипте.
awk '/^            _cand_run="\$CAND"$/,/^            fi$/' "$PROBE" > "$T/join.sh"
if [ ! -s "$T/join.sh" ]; then
    no "в пробе есть склейка списка кандидатов" "блок кода" "не найден"
else
    printf '20860\tlouisvuitton.com\n13335\thcaptcha.com\n' > "$T/sniout"
    printf '# шапка\nhcaptcha.com\nvk.com\n300.ya.ru\nlouisvuitton.com\n' > "$T/cand"
    {
        printf 'CAND="%s"\n' "$T/cand"
        printf 'SNIOUT="%s"\n' "$T/sniout"
        sed 's/^            //' "$T/join.sh"
        printf 'cat "$_cand_run"\n'
    } > "$T/run.sh"
    OUT=$(sh "$T/run.sh" 2>/dev/null)
    eq "первым идёт имя из карты" "louisvuitton.com" "$(printf '%s\n' "$OUT" | sed -n 1p)"
    eq "вторым — второе имя из карты" "hcaptcha.com" "$(printf '%s\n' "$OUT" | sed -n 2p)"
    eq "дубли убраны" "1" "$(printf '%s\n' "$OUT" | grep -c '^hcaptcha.com$')"
    eq "louisvuitton.com не повторён" "1" "$(printf '%s\n' "$OUT" | grep -c '^louisvuitton.com$')"
    eq "комментарии не попали в перебор" "0" "$(printf '%s\n' "$OUT" | grep -c '^#')"
    eq "остальной список на месте" "1" "$(printf '%s\n' "$OUT" | grep -c '^300.ya.ru$')"

    # Карты ещё нет (первая установка) — перебор обязан идти по штатному списку,
    # а не падать и не остаться пустым.
    rm -f "$T/sniout"
    OUT2=$(sh "$T/run.sh" 2>/dev/null)
    eq "без карты берётся штатный список" "hcaptcha.com" "$(printf '%s\n' "$OUT2" | grep -v '^#' | sed -n 1p)"
fi

# --- 2. Список кандидатов ----------------------------------------------------
_names=$(grep -vc '^#' "$CANDS")
[ "$_names" -gt 2000 ] \
    && ok "список кандидатов расширен до белого списка целиком ($_names имён)" \
    || no "размер списка кандидатов" ">2000" "$_names"

# Эмпирическая голова не переставлена: на ней держится скорость подбора.
eq "первым кандидатом остаётся hcaptcha.com" "hcaptcha.com" \
    "$(grep -v '^#' "$CANDS" | sed -n 1p)"
eq "300.ya.ru остаётся в первой десятке" "1" \
    "$(grep -v '^#' "$CANDS" | head -10 | grep -c '^300.ya.ru$')"

# Имя, ради которого всё затевалось, в списке есть.
eq "louisvuitton.com в кандидатах" "1" "$(grep -c '^louisvuitton.com$' "$CANDS")"

# Дубли: каждая лишняя строка — лишняя проба к чужому серверу с линии человека.
_dups=$(grep -v '^#' "$CANDS" | sort | uniq -d | head -5)
if [ -z "$_dups" ]; then
    ok "дублей в списке кандидатов нет"
else
    no "дублей нет" "пусто" "$(printf '%s' "$_dups" | tr '\n' ' ')"
fi

# Мусор в списке кандидатов = проба уходит в никуда и тратит минуты.
_bad=$(grep -v '^#' "$CANDS" | grep -vE '^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$' | head -3)
if [ -z "$_bad" ]; then
    ok "в списке только доменные имена"
else
    no "в списке только доменные имена" "без мусора" "$(printf '%s' "$_bad" | tr '\n' ' ')"
fi

# --- 3. Мишени ---------------------------------------------------------------
# Формат: id<TAB>asn<TAB>подтверждено<TAB>провайдер<TAB>ip<TAB>порт<TAB>имя.
_badrows=$(grep -v '^#' "$TARGETS" | awk -F'\t' 'NF && (NF != 7 || $2 !~ /^[0-9]+$/ || $5 == "" || $6 !~ /^[0-9]+$/) { print NR": "$0 }' | head -3)
if [ -z "$_badrows" ]; then
    ok "строки мишеней разбираются"
else
    no "строки мишеней разбираются" "7 полей, числовые asn и порт" "$(printf '%s' "$_badrows" | head -1)"
fi
eq "мишени подкастовой сети на месте" "2" \
    "$(awk -F'\t' '$2=="20860" && $7=="audio.thisisdistorted.com"' "$TARGETS" | wc -l | tr -d ' ')"

# Хост подкастов обязан попадать в профиль: без этого подстановка имени не
# применяется, сколько бы карта ни знала.
eq "домен подкастов в дополнительных" "1" \
    "$(grep -c '^thisisdistorted.com$' "$HERE/files/lists/extra-domains.txt")"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
