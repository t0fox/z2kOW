#!/bin/sh
# tests/test_reinstall_keeps_service_stopped.sh — остановленный сервис не
# считается поломкой установки.
#
# ЖАЛОБА ИЗ ПОЛЯ (16.09.2026). Останавливаешь сервис кнопкой в панели или
# пунктом меню, потом запускаешь переустановку первым пунктом меню — она НИКОГДА
# не завершается удачей: в конце сервис не стартует, установщик засчитывает это
# за провал и откатывает всю переустановку на прежнее дерево. Запустишь сервис
# перед переустановкой — всё проходит.
#
# Причина не в переустановке. ENABLED=0 ставит сам человек, и мы бережём этот
# флаг через переустановку намеренно (иначе остановленный сервис воскресал бы
# каждой ночной обновой). А проверка в конце спрашивала только «бежит ли
# nfqws2», не спрашивая, ДОЛЖЕН ли он бежать: init при ENABLED=0 честно отвечает
# «zapret2 is disabled in config», проверка считала это провалом, и вся работа
# откатывалась.
#
# Тот же класс ошибки уже ловили в шаге обновления (au_step_restart_service) —
# здесь он оставался в пути переустановки. Оба места сверяются ниже, чтобы не
# разошлись снова.
#
# POSIX sh.

HERE=$(cd "$(dirname "$0")/.." && pwd)
STRAT="$HERE/lib/strategies.sh"
AU="$HERE/lib/auto_update.sh"

PASS=0; FAIL=0
ok() { PASS=$((PASS+1)); printf '[PASS] %s\n' "$1"; }
no() { FAIL=$((FAIL+1)); printf '[FAIL] %s (want=%s got=%s)\n' "$1" "$2" "$3"; }
eq() { if [ "$2" = "$3" ]; then ok "$1"; else no "$1" "$2" "$3"; fi; }

for f in "$STRAT" "$AU"; do
    [ -f "$f" ] || { printf '[FAIL] нет %s\n' "$f"; exit 1; }
done

T=$(mktemp -d "${TMPDIR:-/tmp}/reinst.XXXXXX") || exit 1
trap 'rm -rf "$T"' EXIT

# Вырезаем сторож вместе с перезапуском и проверкой живости — то есть ровно тот
# хвост, что решает судьбу переустановки.
awk '/^    # ЧЕЛОВЕК ОСТАНОВИЛ СЕРВИС/,/^}$/' "$STRAT" > "$T/tail.sh"
if [ ! -s "$T/tail.sh" ]; then
    no "в lib/strategies.sh есть сторож остановленного сервиса" "блок" "не найден"
else
    mk() { # mk <ENABLED> <бежит ли nfqws2 после restart: 1/0>
        printf 'ENABLED=%s\n' "$1" > "$T/config"
        cat > "$T/run.sh" <<EOF
zapret_config="$T/config"
init_script="$T/init"
safe_config_read() {
    _v=\$(grep "^\$1=" "\$2" 2>/dev/null | head -1 | cut -d= -f2-)
    [ -n "\$_v" ] || _v="\$3"
    printf %s "\$_v"
}
print_info()    { printf 'INFO %s\n' "\$*"; }
print_success() { printf 'OK %s\n' "\$*"; }
print_error()   { printf 'ERR %s\n' "\$*"; }
purge_stale_keepalive_fw() { :; }
is_zapret2_running() { [ "$2" = 1 ]; }
sleep() { :; }
EOF
        printf '#!/bin/sh\necho "restart" >> "%s/calls"\n' "$T" > "$T/init"
        chmod +x "$T/init"
        : > "$T/calls"
        # Хвост живёт ВНУТРИ функции: там есть local и return, вне функции
        # оболочка на них ругается, и проверялась бы не логика, а ошибка.
        printf 'tail_run() {\n' >> "$T/run.sh"
        sed '$d' "$T/tail.sh" >> "$T/run.sh"      # без закрывающей } самой функции
        printf '}\ntail_run; echo "rc=$?"\n' >> "$T/run.sh"
    }
    run() { sh "$T/run.sh" 2>&1; }
    calls() { wc -l < "$T/calls" | tr -d ' '; }

    # 1. Человек остановил сервис: переустановка обязана пройти.
    mk 0 0
    out=$(run)
    case "$out" in
        *"rc=0"*) ok "при ENABLED=0 применение стратегий завершается успехом" ;;
        *) no "при ENABLED=0 успех" "rc=0" "$out" ;;
    esac
    case "$out" in
        *"остановлен вами"*) ok "человеку сказано, что сервис оставлен остановленным" ;;
        *) no "объяснение для человека" "строка про остановку" "$out" ;;
    esac
    case "$out" in
        *"ERR"*) no "нет ложной ошибки" "без print_error" "$out" ;;
        *) ok "ложной ошибки «сервис не запустился» нет" ;;
    esac
    eq "остановленный сервис не дёргают перезапуском" "0" "$(calls)"

    # 2. Сервис включён и поднялся — прежнее поведение.
    mk 1 1
    out=$(run)
    case "$out" in
        *"rc=0"*) ok "при ENABLED=1 и живом сервисе — успех" ;;
        *) no "при ENABLED=1 успех" "rc=0" "$out" ;;
    esac
    eq "включённый сервис перезапускается" "1" "$(calls)"

    # 3. Сервис включён, но НЕ поднялся — это настоящая поломка, и она обязана
    #    остаться поломкой: иначе установщик молча оставит человека без обхода.
    mk 1 0
    out=$(run)
    case "$out" in
        *"rc=1"*) ok "при ENABLED=1 и мёртвом сервисе — провал, как и раньше" ;;
        *) no "при ENABLED=1 и мёртвом сервисе провал" "rc=1" "$out" ;;
    esac
    case "$out" in
        *"не запустился"*) ok "про настоящую поломку сказано" ;;
        *) no "про настоящую поломку сказано" "строка про незапуск" "$out" ;;
    esac
fi

# Шаг обновления закрыл этот же класс раньше — обе стороны обязаны смотреть на
# ENABLED, иначе одна из них снова начнёт откатывать чужую работу.
eq "шаг restart-service сверяется с ENABLED" "1" \
    "$(grep -c "_rs_en=.*ENABLED=" "$AU")"
eq "путь переустановки сверяется с ENABLED" "1" \
    "$(grep -c '_svc_enabled=$(safe_config_read "ENABLED"' "$STRAT")"

printf '\nPASSED: %d\nFAILED: %d\n' "$PASS" "$FAIL"
[ "$FAIL" = 0 ]
