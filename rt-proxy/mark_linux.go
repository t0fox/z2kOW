//go:build linux

package main

import "syscall"

// Только стандартная библиотека: ради одной константы тащить golang.org/x/sys
// в проект без внешних зависимостей незачем — syscall на Linux знает и
// SOL_SOCKET, и SO_MARK.

// markControl ставит SO_MARK на сокет ДО подключения.
//
// ЗАЧЕМ. Соединения этого моста — исходящий трафик самого роутера, и движок
// обхода (d2k) видит их как обычную цель: подсматривает SNI `ps1.blockme.site`,
// заводит поиск и ставит на них планы десинхронизации. Это трата бюджета зондов
// на СОБСТВЕННЫЙ работающий туннель и, хуже того, вмешательство в него.
// Поймано 12.09.2026 по журналу d2k на роутере автора: бесконечные «по
// ps1.blockme.site начинаю поиск».
//
// Метка — тот же рычаг, которым движок уже исключает свои собственные пакеты:
// первым правилом исходящей цепочки стоит `-m mark --mark <метка> -j RETURN`, и
// помеченный пакет уходит мимо очереди нетронутым. Сплошное исключение всего
// локального трафика не годится: зонды свойств у d2k намеренно НЕПОМЕЧЕННЫЕ,
// иначе только что поставленный план к ним не применится и они будут мерить
// линию без обхода.
//
// Ноль означает «не метить» — поведение до этой правки, и оно остаётся
// умолчанием: метка принадлежит чужому продукту, и включать её здесь без
// ведома того, кто настраивает роутер, нельзя.
func markControl(mark int) func(string, string, syscall.RawConn) error {
	if mark <= 0 {
		return nil
	}
	return func(_, _ string, c syscall.RawConn) error {
		var serr error
		if err := c.Control(func(fd uintptr) {
			serr = syscall.SetsockoptInt(int(fd), syscall.SOL_SOCKET, syscall.SO_MARK, mark)
		}); err != nil {
			return err
		}
		return serr
	}
}
